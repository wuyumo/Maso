import Foundation

// Synthetic plans plus the bundled exercises.json next to this source tree.
// Does not read maso-data.json, Health, or coach sessions, and does not write them.
//
// Do not compile this file against the Mac Settings.swift. That file references
// WorkoutCompletion, MealCheckIn, DailyWellnessGoal, DietPreferences, DailyDietPlan,
// BodyActivityHealthState, ExternalWorkout, and PolarEntitlement, so a standalone
// swiftc command fails before any assertion runs. The Mac entry is scheme
// MasoCoachSwapTests, which sets MASO_COACH_SWAP_TEST before MasoApp starts.
// Do not use scheme Maso for this test: it has no launch environment, so the
// host calls DataStore.bootstrap(). This script is not an Xcode target member.

private var failures = 0
private func check(_ ok: Bool, _ message: String) {
    if !ok {
        failures += 1
        fputs("FAIL \(message)\n", stderr)
    }
}

private func step(_ id: String, _ exercise: String, sets: Int, reps: Int, weight: Double?,
                  rest: Int, setWeights: [Double?]? = nil) -> PlanStep {
    var step = PlanStep(id: id, exerciseId: exercise, sets: sets, reps: reps, weight: weight,
                        restBetweenSets: rest, rest: 15)
    step.setReps = [reps, reps + 1]
    step.setDurations = [nil, 3]
    step.setWeights = setWeights
    step.duration = nil
    return step
}

@main
enum CoachSwapCheck {
    static func main() {
        let catalogURL = URL(fileURLWithPath: CommandLine.arguments.dropFirst().first
            ?? "Maso/Resources/exercises.json")
        let data = try! Data(contentsOf: catalogURL)
        let library = ExerciseLibrary.load(data: data)
        check(library.count > 100, "catalog loaded from \(catalogURL.path) count=\(library.count)")
        let byId = Dictionary(uniqueKeysWithValues: library.map { ($0.id, $0) })
        guard let bench = byId["bench_press_barbell"], let machine = byId["bench_press_machine"] else {
            check(false, "bundled catalog is missing bench_press_barbell or bench_press_machine")
            fputs("\(failures) failed\n", stderr)
            exit(1)
        }
        let candidates = library.filter { !$0.isNiche }
        let created = Date(timeIntervalSince1970: 1_700_000_000)
        let used = Date(timeIntervalSince1970: 1_700_100_000)
        var push = Plan(id: "push", name: "Push", steps: [
            step("s1", bench.id, sets: 4, reps: 6, weight: 100, rest: 120, setWeights: [90, 100, 110, 100]),
            step("s2", bench.id, sets: 3, reps: 10, weight: 80, rest: 90),
            step("s3", "bench_press_neutral_grip_dumbbell", sets: 3, reps: 12, weight: 30, rest: 60),
            step("s4", "barbell_row", sets: 4, reps: 8, weight: 70, rest: 90),
        ], createdAt: created, updatedAt: created, autoGenerated: true, lastUsedAt: used, source: .custom,
           rationale: "keep me", constraints: [PlanConstraint(kind: .focus, value: "chest", label: "Chest")])
        push.preservesExerciseVariants = true
        var legs = Plan(id: "legs", name: "Legs", steps: [
            step("l1", "barbell_row", sets: 5, reps: 5, weight: 140, rest: 180),
        ], createdAt: created, updatedAt: created)
        legs.preservesExerciseVariants = false
        let plans = [push, legs]
        let history = [
            SetRecord(id: "rec", exerciseId: bench.id, exerciseName: "Bench Press", category: .strength,
                      weight: 100, reps: 6, duration: nil, performedAt: used, planId: "push",
                      planName: "Push", workoutSessionID: "session-keep")
        ]
        let today = Plan(id: "today", name: "Today", steps: [
            step("t1", bench.id, sets: 1, reps: 5, weight: 100, rest: 90)
        ], createdAt: created, updatedAt: created)

        let context = CoachEquipmentSwap.Context(
            plans: plans, library: library, candidates: candidates, availableEquipment: [],
            focusedPlanId: nil, conversationPlanIds: [], onlyModifyName: nil, languageCode: "zh-Hans")
        guard case .preview(let proposal) = CoachEquipmentSwap.interpret(
            "把所有练胸的杠铃器械都换成machine", context: context) else {
            check(false, "expected a preview")
            fputs("\(failures) failed\n", stderr)
            exit(1)
        }
        check(proposal.lines.map(\.stepId) == ["s1", "s2"], "only the two chest barbell steps \(proposal.lines.map(\.stepId))")
        check(proposal.lines.allSatisfy { $0.toExerciseId == machine.id }, "replacement is the real machine press")
        check(proposal.requiresConfirmation, "preview does not write")

        var persistCalls = 0
        let failed = CoachEquipmentSwap.applyTransaction(
            plans: plans, sets: history, aiTodayPlan: today, proposal: proposal,
            allowedExerciseIds: Set(candidates.map(\.id))
        ) { _ in
            persistCalls += 1
            return false
        }
        if case .failed(.persist) = failed.result {} else { check(false, "persist failure \(failed.result)") }
        check(persistCalls == 1, "failure still attempts one write")
        check(failed.plans == plans, "failed transaction returns the original plans")
        check(failed.sets == history, "history is not rewritten")
        check(failed.aiTodayPlan == today, "today plan is not rewritten")
        check(failed.previousPlans == nil, "no undo snapshot after a failed write")

        // Caller rollback: memory plans match the pre-swap copy when save returns false.
        var memoryPlans = plans
        var parallelMarker = 7
        let rolled = CoachEquipmentSwap.applyTransaction(
            plans: memoryPlans, sets: history, aiTodayPlan: today, proposal: proposal,
            allowedExerciseIds: Set(candidates.map(\.id))
        ) { newPlans in
            memoryPlans = newPlans
            parallelMarker += 1
            let ok = false
            if !ok { memoryPlans = plans }
            return ok
        }
        memoryPlans = rolled.plans
        check(memoryPlans == plans, "caller restores plans after a refused write")
        check(parallelMarker == 8, "a parallel in-memory update is kept")
        check(history[0].workoutSessionID == "session-keep" && history[0].weight == 100, "history value stays")

        persistCalls = 0
        let directory = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("coach-swap-check-\(UUID().uuidString)")
        try! FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let applied = CoachEquipmentSwap.applyTransaction(
            plans: plans, sets: history, aiTodayPlan: today, proposal: proposal,
            allowedExerciseIds: Set(candidates.map(\.id))
        ) { newPlans in
            persistCalls += 1
            let enc = JSONEncoder()
            enc.dateEncodingStrategy = .iso8601
            let blob = try! enc.encode(newPlans)
            try! blob.write(to: directory.appendingPathComponent("plans.json"), options: .atomic)
            return true
        }
        guard case .applied(let written) = applied.result else {
            check(false, "apply \(applied.result)")
            fputs("\(failures) failed\n", stderr)
            exit(1)
        }
        check(persistCalls == 1, "one successful write")
        let saved = written[0]
        check(saved.id == "push" && saved.name == "Push" && saved.createdAt == created && saved.lastUsedAt == used, "plan identity and dates kept")
        check(saved.autoGenerated == true && saved.source == .custom && saved.rationale == "keep me", "source and rationale kept")
        check(saved.constraints == push.constraints && saved.preservesExerciseVariants == true, "constraints and variant flag kept")
        check(saved.steps.map(\.id) == ["s1", "s2", "s3", "s4"], "order kept, including duplicates")
        check(saved.steps[0].exerciseId == machine.id && saved.steps[1].exerciseId == machine.id, "both barbell rows replaced")
        check(saved.steps[0].weight == nil && saved.steps[0].setWeights == nil, "uniform and per-set load cleared")
        check(saved.steps[0].sets == 4 && saved.steps[0].reps == 6 && saved.steps[0].setReps == [6, 7]
                && saved.steps[0].setDurations == [nil, 3] && saved.steps[0].restBetweenSets == 120
                && saved.steps[0].rest == 15, "sets, reps, duration overrides, and rest kept")
        check(saved.steps[1].sets == 3 && saved.steps[1].reps == 10 && saved.steps[1].weight == nil, "second instance keeps its own reps")
        check(saved.steps[2].exerciseId == "bench_press_neutral_grip_dumbbell" && saved.steps[2].weight == 30, "dumbbell untouched")
        check(saved.steps[3].exerciseId == "barbell_row" && saved.steps[3].weight == 70, "row untouched")
        check(written[1].steps[0].exerciseId == "barbell_row" && written[1].preservesExerciseVariants == false, "other routine untouched")
        check(applied.sets == history && applied.aiTodayPlan == today, "history and today plan returned unchanged")
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        let reopened = try! decoder.decode([Plan].self, from: Data(contentsOf: directory.appendingPathComponent("plans.json")))
        check(reopened[0].steps[0].exerciseId == machine.id && reopened[0].steps[0].weight == nil, "reopen keeps the swap and cleared load")
        check(reopened[0].preservesExerciseVariants == true && reopened[0].steps[2].weight == 30, "reopen keeps the other fields")

        persistCalls = 0
        let again = CoachEquipmentSwap.applyTransaction(
            plans: written, sets: history, aiTodayPlan: today, proposal: proposal,
            allowedExerciseIds: Set(candidates.map(\.id))
        ) { _ in persistCalls += 1; return true }
        if case .alreadyApplied = again.result {} else { check(false, "second apply \(again.result)") }
        check(persistCalls == 0 && again.plans == written, "retry does not write again")

        var raced = plans
        raced[0].steps[0].exerciseId = "bench_press_neutral_grip_dumbbell"
        persistCalls = 0
        let conflict = CoachEquipmentSwap.applyTransaction(
            plans: raced, sets: history, aiTodayPlan: today, proposal: proposal,
            allowedExerciseIds: Set(candidates.map(\.id))
        ) { _ in persistCalls += 1; return true }
        if case .failed(.conflict) = conflict.result {} else { check(false, "conflict \(conflict.result)") }
        check(persistCalls == 0 && conflict.plans[0].steps[1].exerciseId == bench.id, "conflict does not partially edit")

        check(CoachEquipmentSwap.chatFollowUp("就这样改") == .confirm, "natural confirm")
        check(CoachEquipmentSwap.chatFollowUp("确认！") == .confirm, "confirm with punctuation")
        check(CoachEquipmentSwap.chatFollowUp("不用改了") == .cancel, "natural cancel")
        check(CoachEquipmentSwap.chatFollowUp("撤销这次") == .undo, "natural undo")
        check(CoachEquipmentSwap.chatFollowUp("帮我排一个练胸的计划") == nil, "unrelated chat is not a swap command")
        check(CoachEquipmentSwap.chatFollowUp("确认，但是只改第一个动作不要动别的") == nil, "a longer mixed sentence is not a bare confirm")
        if case .notHandled = CoachEquipmentSwap.interpret("今天练什么", context: context) {} else {
            check(false, "unrecognized chat must stay on the normal coach path")
        }

        try? FileManager.default.removeItem(at: directory)
        if failures == 0 {
            fputs("OK catalog \(library.count)\n", stdout)
            exit(0)
        }
        fputs("\(failures) failed\n", stderr)
        exit(1)
    }
}
