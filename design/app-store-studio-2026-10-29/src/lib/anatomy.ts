/**
 * Poster-level muscle groups -> the polygon ids that light up, mirroring
 * `expandAnatomyMuscles` in Anatomy.swift (e.g. `.back` lights trapezius,
 * lats and lower back; `.chest` lights both pec polygons).
 */
